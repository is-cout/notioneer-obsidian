function inlineWorkerPlugin(extraConfig) {
  return {
    name: 'esbuild-plugin-inline-worker',

    setup(build) {
      build.onLoad(
        {filter: /\.worker\.(js|jsx|ts|tsx)$/},
        async ({path: workerPath}) => {
          // let workerCode = await fs.promises.readFile(workerPath, {
          //   encoding: 'utf-8',
          // });
          const workerLookup = {
            "indexer.worker.ts": "Superstate Indexer",
            "runner.worker.ts": "Superstate Runner",
            "search.worker.ts": "Superstate Search"
          }
          const workerName = workerPath.split('/').pop();
          

          let workerCode = await buildWorker(workerPath, extraConfig);
          return {
            contents: `import inlineWorker from '__inline-worker'
export default function Worker() {
  return inlineWorker(${JSON.stringify(workerCode)}, ${ JSON.stringify({name: workerLookup[workerName]})});
}
`,
            loader: 'js',
          };
        }
      );
      

      const inlineWorkerFunctionCode = `
export default function inlineWorker(scriptText, name) {
  let blob = new Blob([scriptText], {type: 'text/javascript'});
  let url = URL.createObjectURL(blob);
  let worker = new Worker(url, name);
  URL.revokeObjectURL(url);
  return worker;
}
`;

      build.onResolve({filter: /^__inline-worker$/}, ({path}) => {
        return {path, namespace: 'inline-worker'};
      });
      build.onLoad({filter: /.*/, namespace: 'inline-worker'}, () => {
        return {contents: inlineWorkerFunctionCode, loader: 'js'};
      });
    },
  };
}



const cacheDir = path.resolve('node_modules/.cache/esbuild-plugin-inline-worker');
fs.mkdirSync(cacheDir, { recursive: true });

async function buildWorker(workerPath, extraConfig) {
  let scriptNameParts = path.basename(workerPath).split('.');
  scriptNameParts.pop();
  scriptNameParts.push('js');
  let scriptName = scriptNameParts.join('.');
  let bundlePath = path.resolve(cacheDir, scriptName);

  if (extraConfig) {
    delete extraConfig.entryPoints;
    delete extraConfig.outfile;
    delete extraConfig.outdir;
    delete extraConfig.workerName;
  }

  
  await esbuild.build({
    entryPoints: [workerPath],
    bundle: true,
    minify: true,
    outfile: bundlePath,
		define: {
			process: 'process',
		},
    target: 'es2020',
    format: 'cjs',
    plugins: [jszipScriptPolyfillPlugin],
    ...extraConfig,
  });

  return fs.promises.readFile(bundlePath, {encoding: 'utf-8'});
}



// jszip ships a prebundled browserify build whose `immediate`/`setimmediate`
// polyfills sniff for the IE8 `script.onreadystatechange` trick and, when it is
// present, schedule tasks by injecting <script> elements. Every engine Obsidian
// runs on reports that property as absent, so the branch is already dead code —
// but its `createElement("script")` calls still trip the Obsidian community
// plugin scanner. Renaming the probed element keeps the sniff false and leaves
// no script element construction in the bundle.
//
// The same `setImmediate` polyfill compiles a non-function argument with
// `new Function`. jszip only ever passes functions, so that branch is dead too;
// it now throws instead, which keeps dynamic code execution out of the bundle.
const jszipScriptPolyfillPlugin = {
	name: 'strip-jszip-script-polyfill',
	setup(build) {
		build.onLoad({ filter: /jszip[\\/]dist[\\/]jszip(\.min)?\.js$/ }, async (args) => {
			const source = await fs.promises.readFile(args.path, 'utf8');
			const patches = [
				[/createElement\("script"\)/g, 'createElement("span")'],
				[/\(e=new Function\(""\+e\)\)/g, '(()=>{throw new TypeError("setImmediate expects a function")})()'],
			];
			let contents = source;
			for (const [pattern, replacement] of patches) {
				const next = contents.replace(pattern, replacement);
				if (next === contents) {
					throw new Error(
						`strip-jszip-script-polyfill: ${pattern} not found in ${args.path}. ` +
						`jszip probably changed — re-check the polyfill before shipping.`
					);
				}
				contents = next;
			}
			return { contents, loader: 'js' };
		});
	},
};

let renamePlugin = {
    name: 'rename-styles',
    setup(build) {
        build.onEnd(() => {
            const { outfile } = build.initialOptions;
            const outcss = outfile.replace(/\.js$/, '.css');
            const fixcss = outfile.replace(/main\.js$/, 'styles.css');
            if (fs.existsSync(outcss)) {
                console.log('Renaming', outcss, 'to', fixcss);
                fs.renameSync(outcss, fixcss);
            }
        });
    },
};


