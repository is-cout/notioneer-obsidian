import esbuild from "esbuild";
import { copy } from 'esbuild-plugin-copy';
import fs from 'fs';
import { builtinModules } from 'module';
import process from "process";

// prevDir / demoDir for the preview and demo builds. Optional; CI has no .env.
if (fs.existsSync('.env')) process.loadEnvFile('.env');

const banner =
`/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const demo = (process.argv[2] === 'demo');
const prod = (process.argv[2] === 'production');
const prev = (process.argv[2] === 'preview');
const buildv = prod || prev

// esbuild names the bundled CSS after the entry (main.css); Obsidian loads styles.css.
let renamePlugin = {
    name: 'rename-styles',
    setup(build) {
        build.onEnd(() => {
            const { outfile } = build.initialOptions;
            const outcss = outfile.replace(/\.js$/, '.css');
            const fixcss = outfile.replace(/main\.js$/, 'styles.css');
            if (fs.existsSync(outcss)) {
                console.log('Renaming', outcss, 'to', fixcss);
                fs.renameSync(outcss, fixcss);
            }
        });
    },
};


const outputDir = prev ? process.env.prevDir : demo ? process.env.demoDir : ".";
esbuild.build({
	banner: {
		js: banner,
	},
	entryPoints: ['main.ts'],
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		...builtinModules],
	format: 'cjs',
	watch: !buildv,
	target: 'es2020',
	logLevel: "info",
	sourcemap: buildv ? false : 'inline',
	treeShaking: true,
  minify: true,
	outfile: outputDir+'/main.js',
  define: { 'process.env.NODE_ENV': prod ? '"production"' : '"development"' },
	plugins: [renamePlugin,
		...(buildv ? [copy({
			resolveFrom: 'cwd',
			assets: {
			  from: 'manifest.json',
			  to: outputDir+'/manifest.json',
			},
		  })] : []),
	],
}).catch(() => process.exit(1));
